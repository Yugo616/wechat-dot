import { readFile, writeFile, mkdir, rm } from 'node:fs/promises';
import { resolve } from 'node:path';
import { execFile } from 'node:child_process';
import { promisify } from 'node:util';
const pkg = JSON.parse(await readFile('package.json', 'utf8'));
const version = process.env.WECHAT_DOT_LEGACY_VERSION;
if (!version) throw new Error('Set WECHAT_DOT_LEGACY_VERSION to the previous released version.');
const mac = process.platform === 'darwin', target = resolve('.cache/legacy');
const file = `wechat-dot-${version}-${mac ? 'mac' : 'win'}-${process.arch}.${mac ? 'zip' : 'exe'}`;
const { owner, repo } = pkg.build.publish;
const response = await fetch(`https://github.com/${owner}/${repo}/releases/download/v${version}/${file}`);
if (!response.ok) throw new Error(`Previous release download failed: ${response.status}`);
await mkdir('.cache', { recursive: true });
const asset = resolve('.cache', file); await writeFile(asset, Buffer.from(await response.arrayBuffer()));
await rm(target, { recursive: true, force: true });
const exec = promisify(execFile);
if (mac) await exec('/usr/bin/ditto', ['-x', '-k', asset, target]);
else await exec(asset, ['/S', `/D=${target}`]);
console.log(`Previous released application prepared: ${version}`);
