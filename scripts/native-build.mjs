import { build } from 'esbuild';
import { mkdir, readFile, writeFile, copyFile, cp, rm } from 'node:fs/promises';
import { buildExtension } from './extension.mjs';
import { prepareNode } from './node-runtime.mjs';
import { execFile } from 'node:child_process';
import { promisify } from 'node:util';
const directory = 'dist/native', ui = 'dist/native-ui';
await rm(directory, { recursive: true, force: true });
await Promise.all([mkdir(directory, { recursive: true }), mkdir(ui, { recursive: true })]);
await build({ entryPoints: ['src/native/backend.ts'], outfile: `${directory}/backend.cjs`, bundle: true, minify: true, platform: 'node', target: 'node22', format: 'cjs', external: ['electron', 'original-fs', 'silk-wasm'] });
await build({ entryPoints: ['src/native/preload.ts'], outfile: `${ui}/preload.js`, bundle: true, minify: true, platform: 'browser', target: ['safari15.6', 'chrome109'] });
await build({ entryPoints: ['src/ui/app.ts'], outfile: `${ui}/ui.js`, bundle: true, minify: true, platform: 'browser', target: ['safari15.6', 'chrome109'] });
const html = (await readFile('src/ui/index.html', 'utf8')).replace(/\s*<meta http-equiv="Content-Security-Policy"[^>]*>/, '').replace('<script src="ui.js">', '<script src="preload.js"></script>\n<script src="ui.js">');
await writeFile(`${ui}/index.html`, html);
await copyFile('src/ui/style.css', `${ui}/style.css`); await copyFile('assets/icon.svg', `${ui}/icon.svg`);
await cp('config', `${directory}/config`, { recursive: true });
for (const file of ['LICENSE', 'THIRD_PARTY_NOTICES.md']) await copyFile(file, `${directory}/${file}`);
await cp('node_modules/silk-wasm', `${directory}/node_modules/silk-wasm`, { recursive: true });
await buildExtension(`${directory}/browser-connection`);
const config = JSON.parse(await readFile('config/defaults.json', 'utf8'));
const pkg = JSON.parse(await readFile('package.json', 'utf8'));
await writeFile(`${directory}/app-update.yml`, JSON.stringify({ ...config.updates.feed, updaterCacheDirName: `${pkg.name}-updater` }));
await writeFile(`${directory}/build-info.json`, JSON.stringify({ version: pkg.version }));
if (!process.argv.includes('--no-runtime')) await prepareNode(directory);
await promisify(execFile)(process.execPath, ['node_modules/@tauri-apps/cli/tauri.js', 'icon', 'assets/icon.png', '--output', 'dist/native-icons']);
console.log('Native backend and interface built.');
