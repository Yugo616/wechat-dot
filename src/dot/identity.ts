import { mkdir, readFile, rename, writeFile } from 'node:fs/promises';
import { join } from 'node:path';

export interface BrowserIdentity { name: string; color: string }
// Called only before starting our own profile. Existing login and browser preferences are retained.
export async function prepareBrowserIdentity(directory: string, identity: BrowserIdentity): Promise<void> {
  await mkdir(join(directory, 'Default'), { recursive: true, mode: 0o700 });
  async function edit(file: string, update: (value: any) => void) {
    let value: any = {};
    try { value = JSON.parse(await readFile(file, 'utf8')); }
    catch (error) { if ((error as NodeJS.ErrnoException).code !== 'ENOENT') throw error; }
    update(value);
    await writeFile(file + '.tmp', JSON.stringify(value), { mode: 0o600 });
    await rename(file + '.tmp', file);
  }
  const color = (0xff000000 | parseInt(identity.color.slice(1), 16)) | 0;
  await edit(join(directory, 'Default', 'Preferences'), value => {
    Object.assign(value.profile ??= {}, { name: identity.name, using_default_name: false, using_gaia_name: false });
    const browser = value.browser ??= {};
    Object.assign(browser.theme ??= {}, { user_color: color, user_color2: color });
    (value.autogenerated ??= {}).theme = { ...value.autogenerated?.theme, color };
  });
  await edit(join(directory, 'Local State'), value => {
    const cache = (value.profile ??= {}).info_cache ??= {};
    Object.assign(cache.Default ??= {}, { name: identity.name, is_using_default_name: false, is_using_gaia_name: false });
  });
}

// A visible mark also survives app-mode windows, which do not show Chrome's profile button.
export function markDedicatedPage(identity: BrowserIdentity): void {
  if (window.top !== window) return;
  const key = '__wechatDotIdentity';
  if ((window as any)[key]) return;
  (window as any)[key] = true;
  const title = `${identity.name} · ChatGPT`;
  const update = () => {
    if (document.title !== title) document.title = title;
    if (!document.body || document.getElementById('wechat-dot-identity')) return;
    const badge = document.createElement('div'); badge.id = 'wechat-dot-identity';
    badge.textContent = identity.name;
    badge.title = '这是 WeChat Dot 的专用窗口，日常浏览记录在你原来的浏览器中。';
    Object.assign(badge.style, { position: 'fixed', right: '12px', bottom: '12px', zIndex: '2147483647',
      padding: '7px 11px', borderRadius: '8px', background: identity.color, color: '#fff',
      font: '12px -apple-system, Segoe UI, sans-serif', pointerEvents: 'none' });
    document.body.append(badge);
  };
  new MutationObserver(update).observe(document, { childList: true, subtree: true });
  update();
}
